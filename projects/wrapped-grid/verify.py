#!/usr/bin/env python3
"""Replay finite checks for the toroidal least-period note (stdlib only).

The binary witness is Skotnica's 2016 construction, Theorem 3.20, in bit
notation. The verification code is original; see LICENSE.
"""

from collections import Counter
from itertools import combinations
from math import comb, gcd, lcm


def require(condition, failure):
    """Keep checks active even if Python is run with -O."""
    if not condition:
        raise AssertionError(failure)


def witness(a):
    """Return Skotnica's points for width 2**a, height 2**(2*a-1)."""
    return [
        (x, tag + sum(((x >> i) & 1) << (2 * i + 1) for i in range(a - 1)))
        for x in range(1 << a)
        for tag in (0, 1)
    ]


def multiplier_equation(v, bits):
    """For coefficient v mod 2**bits: divisor, multiplier modulus, inverse."""
    power = v & -v
    if power == 0:
        return 1 << bits, 1, 0
    modulus = (1 << bits) // power
    return power, modulus, pow(v // power, -1, modulus)


def fits(v, generator):
    """Test whether v is an integer multiple of the specified generator."""
    x, y = v
    dx, ix, dy, iy, common_mask = generator
    if x & (dx - 1) or y & (dy - 1):
        return False
    return (((x // dx) * ix - (y // dy) * iy) & common_mask) == 0


def binary_triples(points, a):
    """Return (is_cap, tests_made) from a cyclic membership check.

    In a cyclic 2-group generated by two elements, the difference with larger
    order generates the subgroup. To test if the other difference is a
    multiple, solve the multiplier congruence separately in each coordinate.
    The two solution residues are compatible iff equal modulo the smaller
    of their power-of-two moduli.
    """
    b = 2 * a - 1
    width, height = 1 << a, 1 << b
    require(len(points) == len(set(points)) == 2 * width, "bad point count")
    require(
        all(0 <= x < width and 0 <= y < height for x, y in points),
        "point outside the torus",
    )
    xm = [multiplier_equation(c, a) for c in range(width)]
    ym = [multiplier_equation(c, b) for c in range(height)]
    count = 0
    for i, (x, y) in enumerate(points):
        diffs = []
        for u, v in points[i + 1:]:
            dx, dy = (u - x) % width, (v - y) % height
            tx, mx, ix = xm[dx]
            ty, my, iy = ym[dy]
            generator = (tx, ix, ty, iy, min(mx, my) - 1)
            diffs.append(((dx, dy), max(mx, my), generator))
        for (u, u_order, u_gen), (v, v_order, v_gen) in combinations(diffs, 2):
            count += 1
            if (fits(u, v_gen) if u_order <= v_order else fits(v, u_gen)):
                return False, count
    require(count == comb(len(points), 3), "not all triples were checked")
    return True, count


def direction_examples():
    """Check line families by listing literal distinct generated subgroups."""
    sizes = [
        (2, 1, 1), (2, 3, 3), (2, 3, 4), (2, 3, 5), (2, 4, 7),
        (3, 2, 2), (3, 2, 4), (3, 3, 5), (5, 2, 4), (7, 2, 3),
    ]
    total = 0
    for p, a, b in sizes:
        width, height = p**a, p**b
        subgroups = {
            frozenset(
                (t % width, t * s % height)
                for t in range(lcm(width, height // gcd(s, height)))
            )
            for s in range(0, height, p)
        }
        d = b - a
        expected = width // p if d == 0 else ((d - 1) * (p - 1) + p) * width // p
        require(len(subgroups) == expected, (p, a, b, "direction count"))
        multiplicity = Counter(pt for subgroup in subgroups for pt in subgroup)
        for x in range(1, width):
            power = gcd(x, width)
            for y in range(0, height, p * power):
                require(multiplicity[x, y] == power, (p, a, b, x, y, "multiplicity"))
                total += 1
    return total, len(sizes)


def main():
    corrupted = witness(2)
    corrupted[-1] = (0, 7)  # Three points in column 0 form a forbidden triple.
    require(not binary_triples(corrupted, 2)[0], "negative control did not fail")
    print("Negative control: correctly rejected.")

    all_triples = 0
    for a in range(1, 8):
        points = witness(a)
        is_cap, count = binary_triples(points, a)
        require(is_cap, (a, count, "found a collinear triple"))
        all_triples += count
        print(f"a={a}: {len(points)} points, {count:,} triples passed.")
    require(all_triples == 3_152_140, "unexpected number of triple tests")
    print(f"Total: {all_triples:,} witness triples passed.")

    differences, sizes = direction_examples()
    require((differences, sizes) == (7_366, 10), "unexpected direction test count")
    print(f"Direction count and multiplicities: {differences:,} differences across {sizes} tori passed.")


if __name__ == "__main__":
    main()
